"""Every extracted rate table with its resolved product and how many lines above the table the
product name was found (0 = in the row or header). Writes dev/TABLE_REPORT.md.

    uv run python dev/table_report.py
"""

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "submission"), str(ROOT / "harness")]

from kb.extract.rates import row_labels, row_product, table_facts  # noqa: E402
from kb.facts import build_snapshot  # noqa: E402
from kb.tables import parse_tables  # noqa: E402
from run_eval import load_snapshots  # noqa: E402

HAND_CHECK = [
    "- up=10 rows: the page's tab label (the same line as the table context) sits 10 lines above",
    "  the table after blank and link lines. Correct in every case.",
    "- up=14 HSA (`/personal/savings-account`, `/rates`, 01-04): the tab link",
    "  'Health Savings Account Rates'; the context 'Saving Account Rates' names no product.",
    "- up=18/26 `/checking-offer-lp`, `/tax-checking-offer-lp`: heading '1st Rate Checking'",
    "  followed only by that account's bullets; the table has the checking balance tiers.",
    "- up=8/24 `/business-rates`, `/business/checking-accounts`,",
    "  `/business/business-checking-accounts`:",
    "  'Business 1st Rate Checking Account' with only a glued promo table and promo text between.",
    "  Correct.",
    "- No misattribution found; no fix needed.",
]


def main():
    seen = defaultdict(set)  # (path, context, families, matched, up) -> snapshot numbers
    for snap in load_snapshots(ROOT / "snapshots"):
        sf = build_snapshot(snap, [])
        for page in sf.pages.values():
            if page.kind == "release" or "|" not in page.markdown:
                continue
            for t in parse_tables(page.markdown):
                if not table_facts(t, page, sf.snapshot_id):
                    continue
                found = {}
                for row in t.rows:
                    p, matched, up = row_product(t, row_labels(t, row))
                    if p:
                        found.setdefault((p.family, matched, up), None)
                for family, matched, up in found:
                    seen[(page.path, t.context, family, matched, up)].add(snap.snapshot_id[:2])
    rows = sorted(seen.items(), key=lambda kv: (-kv[0][4], kv[0][0], kv[0][2]))
    lines = [
        "# Extracted rate tables",
        "",
        "Generated by `dev/table_report.py`. `up` = lines above the table where the product name",
        "was found (0 = row or header). Rows with `up` > 5 were checked by hand (see bottom).",
        "",
        "| up | snapshots | page | product | named by | table context |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for (path, ctx, family, matched, up), snaps in rows:
        snapshots = ",".join(sorted(snaps))
        lines.append(f"| {up} | {snapshots} | `{path}` | {family} | {matched[:50]} | {ctx[:40]} |")
    far = [k for k in seen if k[4] > 5]
    lines += [
        "",
        f"{len(seen)} distinct table/product pairs; {len(far)} named more than 5 lines up.",
    ]
    print(lines[-1])
    lines += ["", "## Hand check of names found more than 5 lines up (2026-11-17)", "", *HAND_CHECK]
    (ROOT / "dev/TABLE_REPORT.md").write_text("\n".join(lines) + "\n")
    for k in sorted(far, key=lambda k: -k[4]):
        print(
            f"  up={k[4]:2d} {k[0]:40s} {k[2]:22s} named by {k[3][:60]!r} (context {k[1][:30]!r})"
        )


if __name__ == "__main__":
    main()
